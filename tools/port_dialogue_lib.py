"""Mechanically converts DialogueLibrary.prepareLibraries() (the built-in dialogue lines) from the FFDec AS3 export
into GDScript and splices it into game/src/obj/dialogue/DialogueLibrary.gd between the BEGIN/END markers."""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text(encoding="utf-8")
dst = Path(sys.argv[2])
body = src.split("private function prepareLibraries() : void", 1)[1].split("private function prepareTypeArray", 1)[0]
out = ["func prepareLibraries() -> void:"]
for raw in body.splitlines():
    s = raw.strip()
    if s in ("", "{", "}"):
        continue
    s = s.replace("new DialogueLine(", "DialogueLine.new(").replace("this.", "")
    m = re.fullmatch(r"var (_loc\d+_):Array = new Array\(\);", s)
    if m:
        out.append(f"\tvar {m[1]}: Array = []")
        continue
    m = re.fullmatch(r"var (_loc\d+_):Array;", s)
    if m:
        out.append(f"\tvar {m[1]}: Array = []")
        continue
    m = re.fullmatch(r"\((_loc\d+_) = new Array\(\)\)\.push\((.*)\);", s)
    if m:
        out.append(f"\t{m[1]} = []")
        out.append(f"\t{m[1]}.append({m[2]})")
        continue
    m = re.fullmatch(r"\((_loc\d+_) = (_loc\d+_)\.slice\(\)\)\.push\((.*)\);", s)
    if m:
        out.append(f"\t{m[1]} = {m[2]}.duplicate()")
        out.append(f"\t{m[1]}.append({m[3]})")
        continue
    m = re.fullmatch(r"(?:var )?(_loc\d+_)(?::Array)? = (_loc\d+_)\.slice\(\);", s)
    if m:
        out.append(f"\tvar {m[1]}: Array = {m[2]}.duplicate()" if s.startswith("var") else f"\t{m[1]} = {m[2]}.duplicate()")
        continue
    m = re.fullmatch(r"(_loc\d+_)\.push\((.*)\);", s)
    if m:
        out.append(f"\t{m[1]}.append({m[2]})")
        continue
    m = re.fullmatch(r"(\w+) = new Dictionary\(\);", s)
    if m:
        out.append(f"\t{m[1]} = {{}}")
        continue
    m = re.fullmatch(r"(\w+)\[(.+?)\] = (.*);", s)
    if m:
        key = m[2]
        if key == "OTHER_FINISH":
            key = "OTHER_FINISH"
        out.append(f"\t{m[1]}[{key}] = {m[3]}")
        continue
    raise SystemExit("unhandled line: " + s)
# AS3 hoists local declarations (the decompiler emits some after first use): declare all locals up front.
names = sorted(set(re.findall(r"\b(_loc\d+_)\b", "\n".join(out))), key=lambda n: int(n[4:-1]))
body_lines = []
for line in out[1:]:
    line = re.sub(r"^\tvar (_loc\d+_): Array = ", r"\t\1 = ", line)
    if re.fullmatch(r"\t_loc\d+_ = \[\]", line) and body_lines and False:
        continue
    body_lines.append(line)
out = [out[0]] + [f"\tvar {n}: Array = []" for n in names] + body_lines
gd = "\n".join(out) + "\n"
text = dst.read_text(encoding="utf-8")
a = "# BEGIN generated by tools/port_dialogue_lib.py\n"
b = "# END generated\n"
pre, rest = text.split(a, 1)
_, post = rest.split(b, 1)
dst.write_text(pre + a + gd + b + post, encoding="utf-8", newline="\n")
print(f"{len(out)} lines")
